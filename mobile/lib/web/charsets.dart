import 'dart:convert';

/// Decodes web pages and feeds in the encodings Hebrew sites use, besides UTF-8 and Latin-1.
class Charsets {
  Charsets._();

  static String decode(List<int> bytes, String? charset) {
    switch ((charset ?? 'utf-8').toLowerCase().replaceAll('_', '-')) {
      case 'windows-1255' || 'cp1255':
        return _single(bytes, _cp1255);
      case 'iso-8859-8' || 'iso-8859-8-i' || 'iso8859-8':
        return _single(bytes, _iso88598);
      case 'iso-8859-1' || 'latin1' || 'windows-1252':
        return latin1.decode(bytes, allowInvalid: true);
      default:
        return utf8.decode(bytes, allowMalformed: true);
    }
  }

  /// The charset named in an XML declaration or HTML meta tag near the start of [bytes].
  static String? sniff(List<int> bytes) {
    final head = latin1.decode(bytes.take(2048).toList(), allowInvalid: true);
    final m = RegExp(r'''encoding=["']([\w-]+)["']|charset=["']?([\w-]+)''', caseSensitive: false).firstMatch(head);
    return m == null ? null : (m[1] ?? m[2]);
  }

  /// Decodes [bytes] using [headerCharset] (from Content-Type) or the document's own declaration.
  static String decodeDocument(List<int> bytes, {String? headerCharset}) =>
      decode(bytes, sniff(bytes) ?? headerCharset);

  static String _single(List<int> bytes, List<int> high) {
    final codes = List<int>.generate(bytes.length, (i) {
      final b = bytes[i];
      return b < 0x80 ? b : high[b - 0x80];
    });
    return String.fromCharCodes(codes);
  }

